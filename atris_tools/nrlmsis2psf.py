#!/usr/bin/env python3
"""Convert a downloaded NASA NRLMSIS table to AtRIS PSF."""

import argparse
import logging
import re
from pathlib import Path

import numpy as np

from .cli import (
    HelpFormatter,
    add_logging_arguments,
    add_version_argument,
    configure_logging,
)
from .psf import (
    INNER_RADIUS,
    OUTER_RADIUS,
    PHI_END,
    THETA_END,
    DETECTOR_ID,
    TEMPERATURE,
    DENSITY,
    PRESSURE,
    STATE,
    FIRST_ELEMENT,
    load_psf,
)

HEADER_MARKER = "Year Mon Day"
HEADER_FIELD_PATTERN = re.compile(r"[A-Za-z][A-Za-z0-9.-]*(?:\([^)]*\))?")
TABLE_FIELDS = (
    "Year",
    "Mon",
    "Day",
    "DOY",
    "hour",
    "Heit",
    "Lat",
    "Lon",
    "Oden",
    "N2den",
    "O2den",
    "air",
    "T",
    "Heden",
    "Arden",
    "Hden",
    "Nden",
)
METADATA_COLUMNS = (0, 1, 2, 3, 4, 6, 7)
DUPLICATE_RELATIVE_TOLERANCE = 5.0e-4
PSF_HEADER = """# AtRIS Planet Specification Format (PSF)
#
# General PSF format
#
# This file defines the concentric spherical material layers of the planetary
# model. atris-psf-to-gdml converts it into simulation.gdml, which is the geometry
# loaded by the AtRIS executable. It is an input model, not simulation output.
#
# Radii are measured from the planet's center. Rows are ordered from the center
# outwards, and the final outer radius is used to size the GDML world. Detector
# IDs identify the corresponding layers in AtRIS output.
#
# The material-definition line below is read by the PSF-to-GDML converter. Its
# first token is a compact legacy solid composition written without spaces: each
# chemical symbol is followed by its relative mass weight. The remaining tokens
# name the per-layer material-fraction columns. Nonzero fractions define the
# composition of gas, liquid, or solid layers. The converter normalizes the
# compact solid weights so their mass fractions sum to one.
#
# Columns (1-based):
#   1  inner radius [km]
#   2  outer radius [km]
#   3  starting azimuth phi [rad]
#   4  ending azimuth phi [rad]
#   5  starting polar angle theta [rad]
#   6  ending polar angle theta [rad]
#   7  sensitive-detector ID
#   8  temperature [K]
#   9  density [g/cm3]
#  10  pressure [Pa]
#  11  material state: 0 gas, 1 solid, 2 liquid
#  12+ material mass fractions named by the material-definition line
#
# For backward compatibility, a solid row with all-zero material fractions uses
# the compact solid composition. Comment lines are ignored when the numeric
# table is read.
#
# Earth model generated by atris-nrlmsis-to-psf
#
# This model contains a solid interior, a thin crust, NRLMSIS atmospheric shells,
# and an outer terminating layer. Its solid composition is written compactly as
# O478Si284Al84Fe52Ca37Na28Mg15. For example, O478 means 478 relative mass parts
# oxygen and Si284 means 284 relative mass parts silicon. These weights are
# normalized by the converter.
#
# The remaining material-definition tokens, N O Ar He H, name columns 12-16:
# nitrogen, oxygen, argon, helium, and hydrogen mass fraction, respectively.
O478Si284Al84Fe52Ca37Na28Mg15 N O Ar He H"""
logger = logging.getLogger(__name__)


def _physical_profile(atmosphere):
    return atmosphere[:, [5, 8, 9, 10, 11, 12, 13, 14, 15, 16]]


def _write_psf(data, filename="simulation.psf"):
    altitude = data[:, 0]
    oxygen = data[:, 1]
    nitrogen = data[:, 2] + 0.5 * data[:, 9]
    oxygen_molecules = data[:, 3] + 0.5 * oxygen
    density = data[:, 4]
    temperature = data[:, 5]
    helium = data[:, 6]
    argon = data[:, 7]
    hydrogen = data[:, 8]

    thickness = np.append(np.diff(altitude), altitude[-1] - altitude[-2])
    bottom_radius = 6371.0 + altitude
    top_radius = bottom_radius + thickness

    boltzmann_constant = 1.38064852e-23
    total_pressure = (
        (oxygen_molecules + nitrogen + argon + helium + hydrogen)
        * boltzmann_constant
        * 1_000_000
        * temperature
    )

    atomic_mass_unit = 1.66054e-24
    masses = (
        np.column_stack(
            (
                nitrogen * (2 * 14.0067),
                oxygen_molecules * (2 * 15.9994),
                argon * 39.948,
                helium * 4.0026,
                hydrogen * 1.008,
            )
        )
        * atomic_mass_unit
    )
    mass_fractions = masses / masses.sum(axis=1, keepdims=True)

    atmosphere = np.zeros((len(data), FIRST_ELEMENT + mass_fractions.shape[1]))
    atmosphere[:, INNER_RADIUS] = bottom_radius
    atmosphere[:, OUTER_RADIUS] = top_radius
    atmosphere[:, PHI_END] = 2 * np.pi
    atmosphere[:, THETA_END] = np.pi
    atmosphere[:, DETECTOR_ID] = np.arange(2, len(data) + 2)
    atmosphere[:, TEMPERATURE] = temperature
    atmosphere[:, DENSITY] = density
    atmosphere[:, PRESSURE] = total_pressure
    atmosphere[:, FIRST_ELEMENT:] = mass_fractions

    crust_thickness = 0.02
    upper_boundary = top_radius[-1] + 0.001
    solids = np.zeros((3, atmosphere.shape[1]))
    solids[:, INNER_RADIUS] = (0, 6371.0 - crust_thickness, upper_boundary)
    solids[:, OUTER_RADIUS] = (
        6371.0 - crust_thickness,
        6371.0,
        upper_boundary + crust_thickness,
    )
    solids[:, PHI_END] = 2 * np.pi
    solids[:, THETA_END] = np.pi
    solids[:, DETECTOR_ID] = (0, 1, len(data) + 2)
    solids[:, TEMPERATURE] = 293.15
    solids[:, DENSITY] = 2.7
    solids[:, PRESSURE] = 101325
    solids[:, STATE] = 1

    output = np.vstack((solids[:2], atmosphere, solids[2:]))
    number_format = ["%e"] * output.shape[1]
    number_format[DETECTOR_ID] = "%i"
    np.savetxt(
        filename,
        output,
        fmt=number_format,
        header=PSF_HEADER,
        comments="",
    )


def _read_table(path):
    path = Path(path)
    table = path.read_text(encoding="utf-8")
    lines = table.splitlines()
    header_indices = [
        index for index, line in enumerate(lines) if HEADER_MARKER in line
    ]
    if not header_indices:
        raise ValueError("NRLMSIS table header not found in " + str(path))

    header = lines[header_indices[0]]
    header_fields = [
        field.partition("(")[0] for field in HEADER_FIELD_PATTERN.findall(header)
    ]
    missing = [field for field in TABLE_FIELDS if field not in header_fields]
    if missing:
        raise ValueError(
            "%s is missing NRLMSIS columns: %s" % (path, ", ".join(missing))
        )
    selected_columns = [header_fields.index(field) for field in TABLE_FIELDS]
    altitude_column = header_fields.index("Heit")

    parsed = []
    malformed = []
    for line_number, line in enumerate(
        lines[header_indices[0] + 1 :],
        start=header_indices[0] + 2,
    ):
        row_fields = line.split()
        if not row_fields:
            continue
        altitude = None
        if len(row_fields) > altitude_column:
            try:
                altitude = _altitude_key(row_fields[altitude_column])
            except ValueError:
                pass
        try:
            values = [float(field) for field in row_fields]
        except ValueError:
            if altitude is None:
                raise ValueError(
                    "Could not identify malformed NRLMSIS row in %s:%i"
                    % (path, line_number)
                )
            malformed.append(altitude)
            continue
        parsed.append((line_number, altitude, values))

    if not parsed:
        raise ValueError("No valid NRLMSIS rows found in " + str(path))
    expected_columns = len(header_fields)
    rows = []
    for line_number, altitude, values in parsed:
        if len(values) != expected_columns:
            if altitude is None:
                raise ValueError(
                    "Could not identify malformed NRLMSIS row in %s:%i"
                    % (path, line_number)
                )
            malformed.append(altitude)
            continue
        rows.append([values[index] for index in selected_columns])
    return path, np.asarray(rows), malformed


def _altitude_key(altitude):
    return round(float(altitude), 9)


def _suspicious_rows(atmosphere):
    physical = _physical_profile(atmosphere)
    return ~np.all(np.isfinite(physical), axis=1) | np.any(
        physical[:, 1:] <= 0,
        axis=1,
    )


def merge_nrlmsis(input_paths):
    """Merge compatible NRLMSIS tables into one validated altitude profile."""
    tables = [_read_table(path) for path in input_paths]
    if not tables:
        raise ValueError("At least one NRLMSIS table is required")

    column_count = tables[0][1].shape[1]
    valid_rows = {}
    rejected_rows = {}
    for path, atmosphere, malformed_altitudes in tables:
        if atmosphere.shape[1] != column_count:
            raise ValueError(
                "%s has %i columns; expected %i"
                % (path, atmosphere.shape[1], column_count)
            )
        for altitude in malformed_altitudes:
            rejected_rows.setdefault(altitude, []).append(path)
            logger.warning(
                "Discarding malformed NRLMSIS row at %.3f km from %s",
                altitude,
                path,
            )
        suspicious = _suspicious_rows(atmosphere)
        for row, reject in zip(atmosphere, suspicious):
            altitude = _altitude_key(row[5])
            if reject:
                rejected_rows.setdefault(altitude, []).append(path)
                logger.warning(
                    "Discarding suspicious NRLMSIS row at %.3f km from %s",
                    altitude,
                    path,
                )
                continue
            if altitude in valid_rows:
                previous_path, previous_row = valid_rows[altitude]
                # CCMC prints about four significant digits, so repeated
                # boundary rows can differ in their final printed digit.
                if not np.allclose(
                    previous_row,
                    row,
                    rtol=DUPLICATE_RELATIVE_TOLERANCE,
                    atol=0.0,
                ):
                    raise ValueError(
                        "Conflicting valid NRLMSIS rows at %.3f km in %s and %s"
                        % (altitude, previous_path, path)
                    )
                continue
            valid_rows[altitude] = (path, row)

    missing_replacements = sorted(set(rejected_rows) - set(valid_rows))
    if missing_replacements:
        altitudes = ", ".join("%.3f" % value for value in missing_replacements)
        raise ValueError(
            "Suspicious NRLMSIS rows at %s km have no valid replacement" % altitudes
        )

    altitudes = sorted(valid_rows)
    if len(altitudes) < 2:
        raise ValueError("The merged NRLMSIS profile requires at least two rows")
    merged = np.vstack([valid_rows[altitude][1] for altitude in altitudes])

    reference_metadata = merged[0, METADATA_COLUMNS]
    if not np.allclose(
        merged[:, METADATA_COLUMNS],
        reference_metadata,
        rtol=0.0,
        atol=1.0e-9,
    ):
        raise ValueError(
            "NRLMSIS tables do not use one common date, time, latitude, and longitude"
        )

    differences = np.diff(merged[:, 5])
    step = np.min(differences)
    tolerance = max(1.0e-9, step * 1.0e-6)
    if step <= 0 or not np.allclose(
        differences,
        step,
        rtol=0.0,
        atol=tolerance,
    ):
        raise ValueError(
            "Merged NRLMSIS altitudes are not a complete, uniformly spaced grid"
        )

    logger.info(
        "Merged %i NRLMSIS file(s) into %i rows from %.3f to %.3f km "
        "with a %.3f km step.",
        len(tables),
        len(merged),
        merged[0, 5],
        merged[-1, 5],
        step,
    )
    return merged


def _validate_psf(path, atmosphere_rows):
    output = load_psf(path)
    expected_rows = atmosphere_rows + 3
    expected_columns = FIRST_ELEMENT + 5  # N, O, Ar, He, H
    if output.shape != (expected_rows, expected_columns):
        raise RuntimeError(
            "%s has shape %s; expected (%i, %i)"
            % (path, output.shape, expected_rows, expected_columns)
        )
    atmosphere = output[2:-1]
    physical = np.column_stack(
        (
            atmosphere[:, [TEMPERATURE, DENSITY, PRESSURE]],
            atmosphere[:, FIRST_ELEMENT:],
        )
    )
    if not np.all(np.isfinite(physical)) or np.any(physical <= 0):
        raise RuntimeError(
            "%s contains non-finite, zero, or negative atmospheric values" % path
        )


def convert_nrlmsis(input_paths, output_path):
    """Convert one or more downloaded NRLMSIS tables to an AtRIS PSF."""
    if isinstance(input_paths, (str, Path)):
        input_paths = [input_paths]
    output_path = Path(output_path)
    atmosphere = merge_nrlmsis(input_paths)
    _write_psf(_physical_profile(atmosphere), output_path)
    _validate_psf(output_path, len(atmosphere))
    logger.info("Wrote %s", output_path)
    return output_path


def main():
    """Run the NRLMSIS-to-PSF command."""
    parser = argparse.ArgumentParser(
        formatter_class=HelpFormatter,
        description=(
            "Convert one or more NASA CCMC NRLMSIS text tables into the "
            "Planet Specification Format (PSF) used by AtRIS."
        ),
        epilog=(
            "Downloaded tables from NRLMSISE-00, NRLMSIS 2.0, and NRLMSIS 2.1 "
            "are supported. This command does not download atmosphere data. "
            "Input tables may overlap and may be supplied in any altitude "
            "order, but they must describe the same location and time and "
            "combine into a complete, uniformly spaced altitude grid. With "
            "one input table, the output defaults to the same basename with "
            "a .psf suffix. Multiple input tables require --output. An "
            "existing output file is replaced."
        ),
    )
    parser.add_argument(
        "nrlmsis_output",
        nargs="+",
        type=Path,
        metavar="TABLE",
        help=(
            "Downloaded NRLMSIS text table. Supply multiple tables when the "
            "altitude profile was downloaded in chunks."
        ),
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        metavar="PSF_FILE",
        help=(
            "PSF file to write. Required when more than one input table is " "supplied."
        ),
    )
    add_logging_arguments(parser)
    add_version_argument(parser)
    args = parser.parse_args()
    configure_logging(args.log_level)
    if args.output is None:
        if len(args.nrlmsis_output) > 1:
            parser.error("--output is required with multiple input tables")
        args.output = args.nrlmsis_output[0].with_suffix(".psf")
    convert_nrlmsis(args.nrlmsis_output, args.output)


if __name__ == "__main__":
    main()
