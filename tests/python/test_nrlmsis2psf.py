import logging
import sys

import numpy as np
import pytest

from atris_tools import nrlmsis2psf
from atris_tools.psf2gdml import psf2gdml

NRLMSIS_20_FIELDS = (
    "Year Mon Day DOY hour Heit(km) Lat Lon Oden(cm-3) N2den(cm-3) "
    "O2den(cm-3) air(gm/cm3) T(K) exoT(K) Heden(cm-3) Arden(cm-3) "
    "Hden(cm-3) Nden(cm-3) F107 F107a apdaily ap0-3 ap3-6 ap6-9 "
    "ap9-12 ap12-33 ap33-59"
).split()


def field_name(field):
    return field.partition("(")[0]


def nrlmsis_row(altitude, latitude=10.0, fields=NRLMSIS_20_FIELDS):
    values = {
        "Year": 2012,
        "Mon": 5,
        "Day": 27,
        "DOY": 148,
        "hour": 12,
        "Heit": altitude,
        "Lat": latitude,
        "Lon": 10,
        "Oden": 2,
        "N2den": 3,
        "O2den": 5,
        "air": 7,
        "T": 290,
        "exoT": 1000,
        "Heden": 11,
        "Arden": 13,
        "Hden": 17,
        "Nden": 19,
    }
    row = np.ones(len(fields))
    for index, field in enumerate(fields):
        row[index] = values.get(field_name(field), 1)
    return row


def write_table(path, rows, fields=NRLMSIS_20_FIELDS):
    path.write_text("CCMC output\n" + " ".join(fields) + "\n")
    with path.open("a") as table:
        np.savetxt(table, rows)


@pytest.mark.parametrize(
    "extra_field",
    [None, "AnomOden(cm-3)", "NOden(cm-3)"],
    ids=["NRLMSIS-2.0", "NRLMSISE-00", "NRLMSIS-2.1"],
)
def test_reads_all_ccmc_nrlmsis_formats_by_header(tmp_path, extra_field):
    fields = list(NRLMSIS_20_FIELDS)
    if extra_field:
        fields.insert(11, extra_field)
    table = tmp_path / "nrlmsis.txt"
    write_table(table, [nrlmsis_row(0, fields=fields)], fields)

    _, atmosphere, malformed = nrlmsis2psf._read_table(table)

    assert not malformed
    np.testing.assert_allclose(
        atmosphere[0],
        [2012, 5, 27, 148, 12, 0, 10, 10, 2, 3, 5, 7, 290, 11, 13, 17, 19],
    )


def test_convert_merges_files_and_replaces_suspicious_duplicate(
    tmp_path, monkeypatch, caplog
):
    first = tmp_path / "first.txt"
    second = tmp_path / "second.txt"
    bad_boundary = nrlmsis_row(2)
    bad_boundary[11] = 0
    write_table(first, [nrlmsis_row(0), nrlmsis_row(1), bad_boundary])
    write_table(second, [nrlmsis_row(2), nrlmsis_row(3)])
    output_path = tmp_path / "simulation.psf"

    with caplog.at_level(logging.WARNING, logger="atris_tools.nrlmsis2psf"):
        output = nrlmsis2psf.convert_nrlmsis([second, first], output_path)

    assert output == tmp_path / "simulation.psf"
    header = output.read_text().splitlines()
    assert header[0] == "# AtRIS Planet Specification Format (PSF)"
    assert "# General PSF format" in header
    assert "# Earth model generated by atris-nrlmsis-to-psf" in header
    assert "#   1  inner radius [km]" in header
    assert "#  11  material state: 0 gas, 1 solid, 2 liquid" in header
    assert (
        "#  12+ material mass fractions named by the material-definition line" in header
    )
    assert any("O478 means 478 relative mass parts" in line for line in header)
    assert any("tokens, N O Ar He H, name columns 12-16" in line for line in header)
    material_line = "O478Si284Al84Fe52Ca37Na28Mg15 N O Ar He H"
    material_index = header.index(material_line)
    assert all(line.startswith("#") for line in header[:material_index])
    assert not header[material_index + 1].startswith("#")
    psf = nrlmsis2psf.load_psf(output)
    assert psf.shape == (7, 16)
    np.testing.assert_allclose(psf[2:-1, 0], [6371, 6372, 6373, 6374])
    psf2gdml(output)
    assert (tmp_path / "simulation.gdml").is_file()
    assert "Discarding suspicious NRLMSIS row at 2.000 km" in caplog.text


def test_merge_rejects_suspicious_row_without_valid_replacement(tmp_path):
    table = tmp_path / "bad.txt"
    bad_boundary = nrlmsis_row(2)
    bad_boundary[12] = 0
    write_table(table, [nrlmsis_row(0), nrlmsis_row(1), bad_boundary])

    with pytest.raises(ValueError, match="2.000 km have no valid replacement"):
        nrlmsis2psf.merge_nrlmsis([table])


def test_merge_replaces_malformed_boundary_row(tmp_path, caplog):
    first = tmp_path / "first.txt"
    second = tmp_path / "second.txt"
    write_table(first, [nrlmsis_row(0), nrlmsis_row(1)])
    fields = ["1"] * 27
    fields[5] = "2"
    fields[18] = "*******"
    with first.open("a") as table:
        table.write(" ".join(fields) + "\n")
    write_table(second, [nrlmsis_row(2), nrlmsis_row(3)])

    with caplog.at_level(logging.WARNING, logger="atris_tools.nrlmsis2psf"):
        merged = nrlmsis2psf.merge_nrlmsis([first, second])

    np.testing.assert_allclose(merged[:, 5], [0, 1, 2, 3])
    assert "Discarding malformed NRLMSIS row at 2.000 km" in caplog.text


def test_merge_rejects_missing_altitude_level(tmp_path):
    first = tmp_path / "first.txt"
    second = tmp_path / "second.txt"
    write_table(first, [nrlmsis_row(0), nrlmsis_row(1)])
    write_table(second, [nrlmsis_row(3), nrlmsis_row(4)])

    with pytest.raises(ValueError, match="complete, uniformly spaced grid"):
        nrlmsis2psf.merge_nrlmsis([first, second])


def test_merge_rejects_conflicting_valid_duplicate(tmp_path):
    first = tmp_path / "first.txt"
    second = tmp_path / "second.txt"
    original = nrlmsis_row(1)
    conflicting = nrlmsis_row(1)
    conflicting[11] = 2
    write_table(first, [nrlmsis_row(0), original])
    write_table(second, [conflicting, nrlmsis_row(2)])

    with pytest.raises(ValueError, match="Conflicting valid NRLMSIS rows"):
        nrlmsis2psf.merge_nrlmsis([first, second])


def test_merge_rejects_mismatched_request_parameters(tmp_path):
    first = tmp_path / "first.txt"
    second = tmp_path / "second.txt"
    write_table(first, [nrlmsis_row(0), nrlmsis_row(1)])
    write_table(
        second,
        [nrlmsis_row(2, latitude=20), nrlmsis_row(3, latitude=20)],
    )

    with pytest.raises(ValueError, match="common date, time, latitude"):
        nrlmsis2psf.merge_nrlmsis([first, second])


def test_main_accepts_multiple_input_files(monkeypatch, tmp_path):
    inputs = [tmp_path / "first.txt", tmp_path / "second.txt"]
    output = tmp_path / "atmosphere.psf"
    received = {}

    def record_call(input_paths, output_path):
        received["inputs"] = input_paths
        received["output"] = output_path

    monkeypatch.setattr(nrlmsis2psf, "convert_nrlmsis", record_call)
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "nrlmsis2psf",
            *(str(path) for path in inputs),
            "--output",
            str(output),
        ],
    )

    nrlmsis2psf.main()

    assert received == {"inputs": inputs, "output": output}


def test_main_derives_output_from_one_input(monkeypatch, tmp_path):
    input_path = tmp_path / "earth.txt"
    received = {}

    def record_call(input_paths, output_path):
        received["inputs"] = input_paths
        received["output"] = output_path

    monkeypatch.setattr(nrlmsis2psf, "convert_nrlmsis", record_call)
    monkeypatch.setattr(sys, "argv", ["nrlmsis2psf", str(input_path)])

    nrlmsis2psf.main()

    assert received == {
        "inputs": [input_path],
        "output": tmp_path / "earth.psf",
    }


def test_main_requires_output_for_multiple_inputs(monkeypatch, tmp_path):
    monkeypatch.setattr(
        sys,
        "argv",
        ["nrlmsis2psf", str(tmp_path / "first.txt"), str(tmp_path / "second.txt")],
    )

    with pytest.raises(SystemExit) as exit_info:
        nrlmsis2psf.main()

    assert exit_info.value.code == 2
